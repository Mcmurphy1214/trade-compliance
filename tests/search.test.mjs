import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {searchScore,upcoming} from '../lib/search.ts';
const articles=JSON.parse(readFileSync(new URL('../lib/seed.json',import.meta.url),'utf8'));
assert.equal(articles.filter(a=>searchScore(a,'FF-1')>0).length,1,'许可号定位');
assert(articles.some(a=>a.category==='出口管制'&&searchScore(a,'semicondutor')>0),'英文拼写容错');
assert(articles.some(a=>a.category==='市场准入与产业政策'&&searchScore(a,'FCC认证')>0),'中文同义词');
assert(articles.some(a=>searchScore(a,'英国 半导体')>0),'跨字段组合检索');
assert.equal(articles.filter(a=>searchScore(a,'根本不存在的监管词条')>0).length,0,'无命中结果');
const d=upcoming(articles,'2026-10-30T01:00:00Z',7);
assert.equal(d.length,1,'7日期限窗口');
assert.equal(d[0].days,0,'今日截止');
assert.equal(upcoming(articles,'2026-10-31T01:00:00Z',7).length,0,'排除已过期节点');
assert(articles.every(a=>a.sources.length&&a.sources.every(s=>s.url.startsWith('https://'))),'资讯必须有原文');
const tariff={...articles[0],id:'tariff-search-fixture',title:'欧盟对涉案产品作出最终裁定',category:'关税',eventType:'最终裁定',topics:['反倾销','复审与日落复审'],summary:'',content:'',implications:'',reference:''};
assert(searchScore(tariff,'tariff')>0,'英文关税检索');
assert(searchScore(tariff,'anti-dumping')>0,'反倾销英文检索');
assert(searchScore(tariff,'双反')>0,'双反通称检索');
assert(searchScore(tariff,'sunset review')>0,'日落复审英文组合检索');
assert.equal(searchScore(tariff,'反补贴'),0,'反倾销不可误判为反补贴');
console.log('PASS 14 项检索、期限与信源检查');
