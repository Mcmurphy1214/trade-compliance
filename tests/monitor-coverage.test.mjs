import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {reconcileMonitorCoverage} from '../lib/monitor-coverage.ts';
const config=JSON.parse(readFileSync(new URL('../lib/monitor-config.json',import.meta.url),'utf8'));
const required=config.coveragePolicy.requiredSources;
const all=required.map(s=>`${s.label} ${s.url} 已核对公告原始日期及正文`);
assert(required.some(s=>s.url==='https://aqygzj.mofcom.gov.cn/zhxx/index.html'),'综合信息必须列入核心栏目');
let result=reconcileMonitorCoverage('已完成',['商务部 https://www.mofcom.gov.cn/；中国出口管制信息网首页'],[],required);
assert.equal(result.status,'部分完成','泛称商务部和首页线索不能证明逐栏完成');
assert(result.gaps.some(g=>g.includes('综合信息')),'遗漏栏目必须写入缺口');
result=reconcileMonitorCoverage('已完成',all.filter(s=>!s.includes('/zhxx/')),[],required);
assert.equal(result.status,'部分完成','局首页不能替代综合信息栏目');
result=reconcileMonitorCoverage('已完成',all,['附件未能读取'],required);
assert.equal(result.status,'部分完成','存在附件缺口时不能记为完整核查');
result=reconcileMonitorCoverage('已完成',all.map(s=>s.includes('/zhxx/')?s+' 访问受限':s),[],required);
assert.equal(result.status,'部分完成','失败的栏目访问不能记为完成');
result=reconcileMonitorCoverage('已完成',all,[],required);
assert.equal(result.status,'已完成');
assert.deepEqual(result.gaps,[]);
result=reconcileMonitorCoverage('部分完成',[],['未核查其他机关'],required);
assert.equal(result.status,'部分完成');
assert.deepEqual(result.gaps,['未核查其他机关']);
console.log('PASS monitor coverage: required consultation column, exact source URLs, failed access and incomplete-run handling');
